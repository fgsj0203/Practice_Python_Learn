"""
Média aritmética
Leia 3 notas (valores decimais) e calcule a média aritmética. Exiba o resultado.
"""

# Variables
nota_one = int(input("Note one: "))
nota_two = int(input("Note two: "))
nota_three = int(input("Note three: "))

# Printing values
print(f"Média aritmética: {(nota_one + nota_two + nota_three) / 3}")
